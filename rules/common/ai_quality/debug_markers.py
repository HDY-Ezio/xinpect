# ===== AI-SPEC-04 AI生成标记 =====
def check_ai_spec_04_ai_generated_markers(context) -> List[Dict]:
    """AI-SPEC-04 AI生成标记检测
    检测代码中的"Generated by ChatGPT"等AI来源标注
    """
    results = []
    
    all_files = context.find_files([".py", ".js", ".ts", ".jsx", ".tsx", ".html", ".css"])
    if not all_files:
        return results
    
    ai_marker_patterns = [
        (r'Generated by (?:ChatGPT|GPT|AI|Copilot|Claude|Bard)', 'AI生成标注'),
        (r'(?:Created|Written|Generated) with (?:AI|GPT|ChatGPT|Copilot)', 'AI生成标注'),
        (r'由(?:ChatGPT|GPT|AI|人工智能|大模型)(?:生成|编写|创建)', 'AI生成标注'),
        (r'Code generated by (?:AI|GPT|ChatGPT)', 'AI生成标注'),
        (r'AI-assisted code', 'AI辅助编写标注'),
        (r'prompt.*generated|generated.*prompt', 'Prompt生成标注'),
    ]
    
    all_issues = []
    
    for fpath in all_files:
        content = context.safe_read(fpath)
        if not content:
            continue
        
        lines = content.split('\n')
        rel = os.path.relpath(fpath, context.project_path or context.backend_path or ".")
        
        for pat, desc in ai_marker_patterns:
            for m in re.finditer(pat, content, re.IGNORECASE):
                line_num = content[:m.start()].count('\n') + 1
                all_issues.append({
                    'file': fpath,
                    'rel': rel,
                    'line': line_num,
                    'desc': desc,
                    'snippet': lines[line_num - 1].strip()[:100] if line_num - 1 < len(lines) else "",
                })
    
    if all_issues:
        total = len(all_issues)
        detail_lines = [
            f"{issue['rel']}:{issue['line']} - {issue['desc']}"
            for issue in all_issues[:10]
        ]
        
        results.append({
            'id': 'AI-SPEC-04',
            'name': 'AI生成标记检测',
            'level': 'info',
            'message': f'发现 {total} 处AI生成代码来源标注',
            'detail': '\n'.join(detail_lines),
            'file': all_issues[0]['file'] if all_issues else '',
            'line': all_issues[0]['line'] if all_issues else 0,
            'snippet': all_issues[0]['snippet'] if all_issues else '',
            'fix': '建议人工Review后移除AI生成标注，确保代码经过质量验证',
            'category': 'ai_specific',
            'suggestion_code': '// 错误：代码中保留AI生成标注\n// Generated by ChatGPT\n// This code was written by AI Assistant\nfunction processData() { ... }\n\n// 正确：移除AI标注，代码应经过人工Review\nfunction processData() { ... }',
        })
    
    return results


