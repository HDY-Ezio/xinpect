def _get_local_packages() -> set:
    """获取本地已安装的Python包名称集合（延迟加载并缓存，线程安全）"""
    global _local_packages
    if _local_packages is not None:
        return _local_packages
    with _cache_lock:
        if _local_packages is not None:
            return _local_packages
        _local_packages = set()
        try:
            from importlib.metadata import distributions
            for dist in distributions():
                name = dist.metadata.get('Name', '')
                if name:
                    low = name.lower()
                    _local_packages.add(low)
                    # 添加归一化名称（连字符/点号转下划线）
                    _local_packages.add(low.replace('-', '_').replace('.', '_'))
        except Exception as e:  # noqa: broad exception handling
            pass
        return _local_packages


def _is_vendored_js_file(fpath: str, rel: str, content: str) -> bool:
    """判断是否为第三方/压缩/vendored JS文件（应跳过调试代码检测）
    
    排除规则：
    1. 路径包含 node_modules/、miniprogram_npm/、vendor/、third_party/、libs/
    2. 文件名包含 sdk、min、vendor、ec-canvas 等第三方标识
    3. 文件内容有明显的压缩特征（超长行、无换行的大段代码）
    """
    rel_lower = rel.lower().replace('\\', '/')
    basename = os.path.basename(fpath).lower()
    
    # 1. 路径检查
    vendored_dirs = {'node_modules', 'miniprogram_npm', 'vendor', 
                     'third_party', 'libs', 'lib', 'dist'}
    rel_parts = rel_lower.split('/')
    if any(d in rel_parts for d in vendored_dirs):
        return True
    
    # 2. 文件名特征
    vendored_name_markers = [
        'sdk', '.min.js', '.min.ts', 'vendor', 'ec-canvas',
        'aegis', 'fingerprint', 'protobuf',
    ]
    if any(marker in basename for marker in vendored_name_markers):
        return True
    
    # 3. 压缩特征检测：平均行长超过200字符 或 单行超过500字符
    lines = content.split('\n')
    if len(lines) > 0:
        avg_line_len = len(content) / len(lines)
        if avg_line_len > 200:
            return True
        # 有超过500字符的行（压缩代码典型特征）
        if any(len(line) > 500 for line in lines[:50]):  # 只检查前50行
            return True
    
    return False


# ===== 项目模块名预计算缓存 =====
_project_modules_cache = {}  # {project_path: set(module_names)}

def _get_project_modules(project_path: str, context=None) -> set:
    """预计算项目中所有可被import的模块名（递归扫描，缓存复用，避免逐文件isfile/isdir）

    v4.6.1: 优先复用 context 的 walk 缓存（零 I/O），在内存中过滤排除目录。
           排除规则与原版 os.walk 完全一致，零行为变更。
           无 context 时回退到 os.walk。
    """
    if not project_path or not os.path.isdir(project_path):
        return set()
    if project_path in _project_modules_cache:
        return _project_modules_cache[project_path]

    modules = set()
    _scan_exclude = {'.git', '.svn', 'node_modules', '__pycache__', '.venv', 'venv',
                     'env', '.env', 'dist', 'build', '.eggs', '.tox', '.mypy_cache',
                     '.pytest_cache', '.next', '.nuxt', '.cache', 'site-packages',
                     'vendor', 'third_party'}

    # v4.6.1: 优先用 context 的 walk 缓存（零 I/O），在内存中过滤
    if context is not None and hasattr(context, '_ensure_walk_cache'):
        context._ensure_walk_cache()
    if context is not None and hasattr(context, '_all_walk_cache') and context._all_walk_cache is not None:
        for fpath, rel, f in context._all_walk_cache:
            if not fpath.startswith(project_path):
                continue
            rel_fwd = rel.replace('\\', '/')
            parts = rel_fwd.split('/')[:-1]
            skip = False
            for part in parts:
                if part in _scan_exclude or part.startswith('.'):
                    skip = True
                    break
            if skip:
                continue
            if f.endswith('.py') and f != '__init__.py' and not f.startswith('_'):
                modules.add(f[:-3])
            for part in parts:
                if part and not part.startswith('_'):
                    modules.add(part)
        _project_modules_cache[project_path] = modules
        return modules

    # 回退：自行扫描磁盘（context 不可用时）
    try:
        for root, dirs, files in os.walk(project_path):
            dirs[:] = [d for d in dirs if d not in _scan_exclude and not d.startswith('.')]
            # 所有目录名都可能是模块名（namespace package）
            for d in dirs:
                if not d.startswith('_'):
                    modules.add(d)
            # 所有 .py 文件名（去掉扩展名）都是模块名
            for f in files:
                if f.endswith('.py') and f != '__init__.py' and not f.startswith('_'):
                    modules.add(f[:-3])
    except Exception as e:  # noqa: broad exception handling
        pass

    _project_modules_cache[project_path] = modules
    return modules


# ===== 轻量级 Python import 提取器（v4.6.1） =====
# 专门为 AI-SPEC-01 设计：只提取 import 信息，避免 get_ast_summary 的全量分析
# 相比 get_ast_summary 快 5~10 倍（不计算复杂度、函数、类、try 等）

def _extract_py_imports(content: str):
    """从 Python 源码中提取 import 语句，返回 [(pkg_name, lineno)]
    使用 ast 模块的单次遍历，仅关注 Import / ImportFrom 节点。
    """
    try:
        import ast as _ast
        tree = _ast.parse(content)
    except (SyntaxError, ValueError):
        return []

    imports = []
    for node in _ast.walk(tree):
        if isinstance(node, _ast.Import):
            for alias in node.names:
                pkg = alias.name.split('.')[0]
                imports.append((pkg, node.lineno))
        elif isinstance(node, _ast.ImportFrom):
            if node.module and node.level == 0:  # 非相对导入
                pkg = node.module.split('.')[0]
                imports.append((pkg, node.lineno))
    return imports


