_DISK_CACHE_TTL = 86400  # 24小时过期

def _load_disk_cache(cache_file: str) -> dict:
    """从磁盘加载缓存（带TTL检查）"""
    try:
        if not os.path.isfile(cache_file):
            return {}
        age = _time.time() - os.path.getmtime(cache_file)
        if age > _DISK_CACHE_TTL * 7:  # 文件超过7天不加载
            return {}
        with open(cache_file, 'r', encoding='utf-8') as f:
            data = json.load(f)
        # 过滤掉过期条目
        now = _time.time()
        return {k: v for k, v in data.items()
                if isinstance(v, dict) and now - v.get('ts', 0) < _DISK_CACHE_TTL}
    except Exception as e:  # noqa: broad exception handling
        return {}

def _save_disk_cache(cache_file: str, data: dict):
    """保存到磁盘缓存"""
    try:
        os.makedirs(os.path.dirname(cache_file), exist_ok=True)
        # 只写最新内容，原子写入
        tmp = cache_file + '.tmp'
        with open(tmp, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False)
        os.replace(tmp, cache_file)
    except Exception as e:  # noqa: broad exception handling
        pass

